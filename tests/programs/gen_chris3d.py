# Generates z486/tests/programs/x87_chris3d.asm: Chris's 3D Benchmark's inner sequence
# (BENCH.EXE 3D98..3E0A) over value sets with exact expected results.
import random, struct
from fractions import Fraction

def to_f32_bits(fr):
    # round an exact value to IEEE single, round to nearest even (normal range only)
    if fr == 0:
        return 0
    s = 1 if fr < 0 else 0
    a = -fr if fr < 0 else fr
    e = 0
    while a >= 2:
        a /= 2; e += 1
    while a < 1:
        a *= 2; e -= 1
    m = a * (1 << 23)
    q, r = divmod(m.numerator, m.denominator)
    rem = Fraction(r, m.denominator)
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and q & 1):
        q += 1
    if q == (1 << 24):
        q >>= 1; e += 1
    assert -126 <= e <= 127, e
    return (s << 31) | ((e + 127) << 23) | (q - (1 << 23))

def f32(x):
    return struct.unpack("<I", struct.pack("<f", x))[0]

def val(bits):
    s = -1 if bits >> 31 else 1
    e = (bits >> 23) & 0xFF
    m = bits & 0x7FFFFF
    if e == 0:
        return Fraction(s * m, 1 << 149)
    return s * Fraction((1 << 23) | m, 1) * Fraction(2) ** (e - 150)

def round_bits(fr, bits):
    # round to a 'bits'-bit significand, nearest even
    if fr == 0:
        return fr
    s = -1 if fr < 0 else 1
    a = abs(fr)
    e = 0
    while a >= 2:
        a /= 2; e += 1
    while a < 1:
        a *= 2; e -= 1
    m = a * (1 << (bits - 1))
    q, r = divmod(m.numerator, m.denominator)
    rem = Fraction(r, m.denominator)
    if rem > Fraction(1, 2) or (rem == Fraction(1, 2) and q & 1):
        q += 1
    return s * Fraction(q) * Fraction(2) ** (e - (bits - 1))

random.seed(486)
sets = []
specials = [(0.0, 1.0, 0.0, 0.0), (0.5, 0.5, 2.0, 2.0), (1.0, 0.0, 3.0, -3.0),
            (0.70710678, 0.70710678, 100.0, 100.0), (-0.0, 1.0, 5.0, 0.0),
            (1.0, 1.0, 1e-20, 1e-20), (0.866, 0.5, 1e10, 1e10), (0.25, 0.75, -7.5, 2.5)]
for c, s_, x, y in specials:
    sets.append((f32(c), f32(s_), f32(x), f32(y)))
for i in range(120):
    a = random.uniform(0, 6.2832)
    import math
    c, s_ = math.cos(a), math.sin(a)
    mag = 10 ** random.uniform(-2, 3)
    x, y = random.uniform(-1, 1) * mag, random.uniform(-1, 1) * mag
    sets.append((f32(c), f32(s_), f32(x), f32(y)))
divs = []
for i in range(len(sets)):
    z = f32(random.uniform(1.0, 2000.0))
    n = f32(random.uniform(-30000.0, 30000.0))
    while True:
        q = round_bits(val(n) / val(z), 64)          # FDIVR with PC = 64 bits
        t = int(q)                                   # FISTP, round toward zero
        if abs(q - round(q)) > Fraction(1, 10**6):
            break
        n = f32(random.uniform(-30000.0, 30000.0))
    divs.append((z, n, t))

exp = []
for (c, s_, x, y) in sets:
    # FLDS c; FMULS y; FLDS s; FMULS x; FSUBRP: c*y - s*x (exact products, 64-bit difference)
    r1 = round_bits(val(c) * val(y) - val(s_) * val(x), 64)
    # FLDS c; FMULS x; FLDS s; FMULS y; FADDP: c*x + s*y
    r2 = round_bits(val(c) * val(x) + val(s_) * val(y), 64)
    exp.append((to_f32_bits(r1), to_f32_bits(r2)))

N = len(sets)
out = []
w = out.append
w("; Chris's 3D Benchmark (Phil's DOS Benchmark Pack, MARKS/CHRISB/BENCH.EXE) stopped on the")
w("; MEGA65 with \"Floating Point exception at eip=00003df5\" (DJGPP: invalid, zero divide and")
w("; overflow unmasked): the FPU raised one after FSTP m32 at 3DF2. Its sequence at 3D98..3E0A,")
w("; instruction for instruction, over %d value sets: FDIVR m32, FNSTCW, FLDCW (truncate, 24" % N)
w("; bits), FISTP m32, FLDCW (back), then a rotation's two terms, each FMUL m32 on FLD m32,")
w("; FSUBP / FADDP and FST(P) m32. Every result must be bit-exact (generated with exact")
w("; arithmetic: products exact, sums to 64 bits, then the store's rounding), the control word")
w("; must read back as loaded, and no invalid, zero-divide or overflow flag may be set (masked")
w("; here; on the board they were not). Generated by gen_chris3d.py.")
w("")
w("BITS 32")
w("ORG 0")
w("STATUS_PORT equ 0xE0")
w("DATA_PORT   equ 0xE4")
w("times 0x400 - ($ - $$) db 0x90")
w("start:")
w("    fninit")
w("    fldcw [cw_base]")
w("    xor esi, esi                    ; the set")
w(".loop:")
w("    ; -- 3D98: the projection: n / z, truncated to an integer")
w("    fld dword [div_z + esi * 4]")
w("    fdivr dword [div_n + esi * 4]")
w("    fnstcw [cw_save]")
w("    mov eax, [cw_save]")
w("    mov ah, 0x0c")
w("    mov [cw_new], eax")
w("    fldcw [cw_new]")
w("    fistp dword [res_int + esi * 4]")
w("    fldcw [cw_save]")
w("    mov edx, [res_int + esi * 4]")
w("    add edx, 0x64")
w("    mov [scratch], edx")
w("    mov eax, [cw_save]")
w("    mov [cw_seen + esi * 4], eax")
w("    ; -- 3DD1: the rotation, as BENCH.EXE has it")
w("    mov edi, esi")
w("    shl edi, 4                      ; 16 bytes a set: c, s, x, y")
w("    fld dword [sets + edi]          ; c")
w("    fmul dword [sets + edi + 12]    ; * y")
w("    fld dword [sets + edi + 4]      ; s")
w("    fmul dword [sets + edi + 8]     ; * x")
w("    fsubp st1, st0                  ; c*y - s*x (DE E9 as in BENCH.EXE; objdump: fsubrp)")
w("    mov eax, esi")
w("    fstp dword [res_a + eax * 4]")
w("    fld dword [sets + edi]          ; c")
w("    fmul dword [sets + edi + 8]     ; * x")
w("    fld dword [sets + edi + 4]      ; s")
w("    fmul dword [sets + edi + 12]    ; * y")
w("    faddp st1, st0                  ; c*x + s*y")
w("    fst dword [res_b + eax * 4]")
w("    fstp st0")
w("    fnstsw ax")
w("    or [sw_or], ax")
w("    inc esi")
w("    cmp esi, %d" % N)
w("    jb .loop")
w("")
w("    ; check: flags, control words, results")
w("    mov eax, 0x10000                ; 1xxxx: a flag")
w("    movzx ecx, word [sw_or]")
w("    test ecx, 0x000d                ; IE, ZE, OE")
w("    jnz .fail_flags")
w("    xor esi, esi")
w(".check:")
w("    mov eax, esi")
w("    or eax, 0x20000                 ; 2xxxx: the control word")
w("    cmp word [cw_seen + esi * 4], 0x%04x" % 0x037F)
w("    jne .fail")
w("    mov eax, esi")
w("    or eax, 0x30000                 ; 3xxxx: the integer")
w("    mov edx, [res_int + esi * 4]")
w("    cmp edx, [exp_int + esi * 4]")
w("    jne .fail")
w("    mov eax, esi")
w("    or eax, 0x40000                 ; 4xxxx: c*y - s*x")
w("    mov edx, [res_a + esi * 4]")
w("    cmp edx, [exp_a + esi * 4]")
w("    jne .fail")
w("    mov eax, esi")
w("    or eax, 0x50000                 ; 5xxxx: c*x + s*y")
w("    mov edx, [res_b + esi * 4]")
w("    cmp edx, [exp_b + esi * 4]")
w("    jne .fail")
w("    inc esi")
w("    cmp esi, %d" % N)
w("    jb .check")
w("    fnstcw [cw_save]")
w("    mov eax, 0x60000")
w("    cmp word [cw_save], 0x037f")
w("    jne .fail")
w("    mov al, 1")
w("    out STATUS_PORT, al")
w("    hlt")
w("    jmp $")
w(".fail_flags:")
w("    or eax, ecx")
w(".fail:")
w("    out DATA_PORT, eax")
w("    mov al, 0xff")
w("    out STATUS_PORT, al")
w("    hlt")
w("    jmp $")
w("")
w("align 4")
w("cw_base:  dw 0x037f, 0          ; all masked, 64 bits, nearest")
w("cw_save:  dd 0")
w("cw_new:   dd 0")
w("sw_or:    dd 0")
w("scratch:  dd 0")
w("sets:")
for (c, s_, x, y) in sets:
    w("    dd 0x%08x, 0x%08x, 0x%08x, 0x%08x" % (c, s_, x, y))
w("div_z:")
for z, n, t in divs:
    w("    dd 0x%08x" % z)
w("div_n:")
for z, n, t in divs:
    w("    dd 0x%08x" % n)
w("exp_int:")
for z, n, t in divs:
    w("    dd 0x%08x" % (t & 0xFFFFFFFF))
w("exp_a:")
for a, b in exp:
    w("    dd 0x%08x" % a)
w("exp_b:")
for a, b in exp:
    w("    dd 0x%08x" % b)
w("res_int:  times %d dd 0" % N)
w("res_a:    times %d dd 0" % N)
w("res_b:    times %d dd 0" % N)
w("cw_seen:  times %d dd 0" % N)
open(__import__("os").path.join(__import__("os").path.dirname(__file__), "x87_chris3d.asm"), "w").write("\n".join(out) + "\n")
print("sets", N)

; x87_chris3d with DJGPP's control word (037Fh -> 0372h: invalid, zero divide and overflow
; unmasked), as Chris's 3D Benchmark runs on the board, where z486 takes the 386 routines
; instead of the direct paths; CR0.NE=1 and an #MF handler that counts, records the first
; EIP and status word, clears and returns. Pass: no #MF at all, results as x87_chris3d.
; Fail with #MF: DATA_PORT = 7 << 28 | count << 16 | first EIP (low 16 bits); the status
; word on DATA_PORT just before it.
; Chris's 3D Benchmark (Phil's DOS Benchmark Pack, MARKS/CHRISB/BENCH.EXE) stopped on the
; MEGA65 with "Floating Point exception at eip=00003df5" (DJGPP: invalid, zero divide and
; overflow unmasked): the FPU raised one after FSTP m32 at 3DF2. Its sequence at 3D98..3E0A,
; instruction for instruction, over 128 value sets: FDIVR m32, FNSTCW, FLDCW (truncate, 24
; bits), FISTP m32, FLDCW (back), then a rotation's two terms, each FMUL m32 on FLD m32,
; FSUBP / FADDP and FST(P) m32. Every result must be bit-exact (generated with exact
; arithmetic: products exact, sums to 64 bits, then the store's rounding), the control word
; must read back as loaded, and no invalid, zero-divide or overflow flag may be set (masked
; here; on the board they were not). Generated by gen_chris3d.py.

